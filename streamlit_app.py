@st.cache_data(ttl=300)
def load_data(tick, per="6mo", interval="1d"):
    df = yf.download(tick, period=per, interval=interval, auto_adjust=True, progress=False)
    if isinstance(df.columns, pd.MultiIndex): df.columns = df.columns.get_level_values(0)
    return df
def rsi(data,w=14):
    d=data['Close'].diff(); g=(d.where(d>0,0)).rolling(w).mean(); l=(-d.where(d<0,0)).rolling(w).mean(); return 100-(100/(1+g/l))

def create_pdf(ticker, ltp, rsi_val, sup, res, trend, fii):
    pdf = FPDF()
    pdf.add_page()
    pdf.set_font("Arial", "B", 20)
    pdf.cell(0, 10, f"FinTrade V11 Report - {ticker}", ln=True, align="C")
    pdf.set_font("Arial", "", 12)
    pdf.ln(10)
    pdf.cell(0, 10, f"Date: {pd.Timestamp.now().strftime('%d-%m-%Y %H:%M')}", ln=True)
    pdf.cell(0, 10, f"LTP: {ltp:.2f} | RSI: {rsi_val:.2f}", ln=True)
    pdf.cell(0, 10, f"Support: {sup:.2f} | Resistance: {res:.2f}", ln=True)
    pdf.cell(0, 10, f"Trend: {trend} | FII/DII: {fii}", ln=True)
    pdf.ln(10)
    pdf.set_font("Arial", "B", 10)
    pdf.cell(0, 10, "Generated by FinTrade V11 ULTIMATE - Ayodhya", ln=True, align="C")
    return pdf.output(dest='S').encode('latin-1')

